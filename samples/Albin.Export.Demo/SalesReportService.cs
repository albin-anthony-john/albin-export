using Albin.Export.Documents;

namespace Albin.Export.Demo;

public sealed record SalesRecord(
    int Id,
    string Region,
    string Product,
    DateTime Date,
    int Units,
    decimal Revenue,
    decimal? Margin,
    bool Active);

/// <summary>
/// Builds the already-prepared report models that Albin.Export consumes.
/// The library never queries a database; this service stands in for the application layer.
/// </summary>
public sealed class SalesReportService
{
    public IReadOnlyList<SalesRecord> Rows(int count = 24)
    {
        var regions = new[] { "North", "South", "East", "West" };
        var products = new[] { "Widget", "Gadget", "Doohickey" };
        var rows = new List<SalesRecord>(count);

        for (var i = 0; i < count; i++)
        {
            rows.Add(new SalesRecord(
                i + 1,
                regions[i % regions.Length],
                products[i % products.Length],
                new DateTime(2026, 1, 1, 8, 30, 0, DateTimeKind.Utc).AddDays(i),
                (i * 7 % 40) + 1,
                decimal.Round(100.5m + (i * 13.37m), 2),
                i % 4 == 0 ? null : decimal.Round(0.1m + (i % 9 * 0.03m), 3),
                i % 3 != 0));
        }

        return rows;
    }

    public ExportTable CreateTable(int count = 24)
    {
        var rows = Rows(count);
        return ExportTable
            .Create(rows, "Sales")
            .Column("Id", x => x.Id)
            .Column("Region", x => x.Region)
            .Column("Product", x => x.Product)
            .Column("Date", x => x.Date, format: "yyyy-MM-dd")
            .Column("Units", x => x.Units)
            .Column("Revenue", x => x.Revenue, format: "N2", alignment: ExportAlignment.Right)
            .Column("Margin", x => x.Margin, format: "P1", alignment: ExportAlignment.Right)
            .Column("Active", x => x.Active)
            .WithTotals("Total", null, null, null, rows.Sum(x => x.Units), rows.Sum(x => x.Revenue), null, null)
            .Build();
    }

    public ChartSpec CreateChart() => new(
        ChartType.Bar,
        ["North", "South", "East", "West"],
        [
            ChartSeries.From("2025", [120d, 98d, 143.5d, 77d]),
            new ChartSeries("2026", [150d, 111d, 160d, 91.25d]),
        ])
    {
        Title = "Revenue by region",
        Subtitle = "in thousands",
        XAxisLabel = "Region",
        YAxisLabel = "Revenue",
        ShowValueLabels = true,
    };

    public ExportDocument CreateDocument(int count = 24) => ExportDocument.Builder("Quarterly sales")
        .Subtitle("Q1 2026, all regions")
        .Footer("Generated by Albin.Export")
        .Heading("Summary", 2)
        .Paragraph("The figures below are prepared by the application layer and handed to Albin.Export as DTOs.")
        .Table(CreateTable(count))
        .Chart(CreateChart())
        .Build();
}
