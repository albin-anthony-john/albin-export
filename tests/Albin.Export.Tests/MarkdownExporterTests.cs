using Albin.Export.Abstractions;
using Albin.Export.Documents;
using Albin.Export.Markdown;

namespace Albin.Export.Tests;

public sealed class MarkdownExporterTests
{
    private readonly MarkdownExporter _exporter = new();

    [Fact]
    public void Metadata_is_correct()
    {
        Assert.Equal(ExportFormat.Markdown, _exporter.Format);
        Assert.Equal(".md", _exporter.FileExtension);
        Assert.Equal(ExportContentTypes.Markdown, _exporter.ContentType);
    }

    [Fact]
    public async Task Writes_title_subtitle_headings_and_paragraphs()
    {
        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(TestData.SalesDocument(2)));

        Assert.Contains("# Quarterly sales", markdown, StringComparison.Ordinal);
        Assert.Contains("_Q1 2026, all regions_", markdown, StringComparison.Ordinal);
        Assert.Contains("## Summary", markdown, StringComparison.Ordinal);
        Assert.Contains("Revenue grew across every region.", markdown, StringComparison.Ordinal);
        Assert.Contains("Generated by Albin.Export", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Writes_a_pipe_table_with_alignment_markers()
    {
        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(TestData.SalesTable(2)));
        var lines = markdown.Split('\n', StringSplitOptions.RemoveEmptyEntries);
        var header = Array.FindIndex(lines, l => l.StartsWith("| Id ", StringComparison.Ordinal));

        Assert.True(header >= 0);
        Assert.Contains("---:", lines[header + 1], StringComparison.Ordinal);
        Assert.StartsWith("| 1 | North | Widget |", lines[header + 2], StringComparison.Ordinal);
    }

    [Fact]
    public async Task Alignment_markers_can_be_disabled()
    {
        var markdown = await TestData.RenderTextAsync(
            _exporter,
            TestData.Request(TestData.SalesTable(1), new MarkdownExportOptions { IncludeAlignmentMarkers = false }));

        Assert.DoesNotContain("---:", markdown, StringComparison.Ordinal);
        Assert.Contains("| --- |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Escapes_pipes_backslashes_and_line_breaks_in_cells()
    {
        var table = ExportTable.FromCells(
            ["Value"],
            [["a|b"], ["c\\d"], ["line1\nline2"], ["line1\r\nline2"]]);

        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(table));

        Assert.Contains("| a\\|b |", markdown, StringComparison.Ordinal);
        Assert.Contains("| c\\\\d |", markdown, StringComparison.Ordinal);
        Assert.Contains("| line1<br>line2 |", markdown, StringComparison.Ordinal);
        Assert.Equal(2, markdown.Split("<br>").Length - 1);
    }

    [Fact]
    public async Task Renders_charts_as_a_data_table()
    {
        var document = ExportDocument.Builder("With chart").Chart(TestData.RevenueChart()).Build();
        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(document));

        Assert.Contains("### Revenue by region", markdown, StringComparison.Ordinal);
        Assert.Contains("| Region | 2025 | 2026 |", markdown, StringComparison.Ordinal);
        Assert.Contains("| North | 120 | 150 |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Embeds_images_as_data_uris()
    {
        var document = ExportDocument.Builder("With image")
            .Image(new byte[] { 1, 2, 3 }, "image/png", "alt text")
            .Build();

        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(document));
        Assert.Contains("![alt text](data:image/png;base64,AQID)", markdown, StringComparison.Ordinal);

        var withoutImages = await TestData.RenderTextAsync(
            _exporter,
            TestData.Request(document, new MarkdownExportOptions { EmbedImages = false }));
        Assert.Contains("_[alt text]_", withoutImages, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Page_breaks_become_horizontal_rules()
    {
        var document = ExportDocument.Builder("Paged").PageBreak().Paragraph("after").Build();
        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(document));
        Assert.Contains("---\n", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Writes_a_bold_totals_row()
    {
        var table = ExportTable.Create(TestData.Sales(2), "Sales")
            .Column("Region", x => x.Region)
            .Column("Revenue", x => x.Revenue, format: "N2")
            .WithTotals("Total", 214.37m)
            .Build();

        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(table));
        Assert.Contains("| **Total** | **214.37** |", markdown, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Handles_unicode_and_empty_tables()
    {
        var markdown = await TestData.RenderTextAsync(_exporter, TestData.Request(TestData.UnicodeTable()));
        Assert.Contains("日本語のテキスト", markdown, StringComparison.Ordinal);

        var empty = await TestData.RenderTextAsync(
            _exporter,
            TestData.Request(ExportTable.Empty(["A", "B"], "Empty")));
        Assert.Contains("| A | B |", empty, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Honours_cancellation()
    {
        using var cts = new CancellationTokenSource();
        await cts.CancelAsync();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(
            () => TestData.RenderAsync(_exporter, TestData.Request(TestData.SalesTable(200)), cts.Token));
    }
}
