using Albin.Export.Abstractions;
using Albin.Export.Documents;
using Albin.Export.Word;
using DocumentFormat.OpenXml.Packaging;
using DocumentFormat.OpenXml.Wordprocessing;

namespace Albin.Export.Tests;

public sealed class WordExporterTests
{
    private readonly WordExporter _exporter = new();

    [Fact]
    public void Metadata_is_correct()
    {
        Assert.Equal(ExportFormat.Word, _exporter.Format);
        Assert.Equal(".docx", _exporter.FileExtension);
        Assert.Equal(ExportContentTypes.Word, _exporter.ContentType);
    }

    [Fact]
    public async Task Produces_a_valid_package_with_the_document_text()
    {
        using var stream = await ExportAsync(TestData.Request(TestData.SalesDocument(3)));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);
        var text = Body(package).InnerText;

        Assert.Contains("Quarterly sales", text, StringComparison.Ordinal);
        Assert.Contains("Q1 2026, all regions", text, StringComparison.Ordinal);
        Assert.Contains("Summary", text, StringComparison.Ordinal);
        Assert.Contains("Revenue grew across every region.", text, StringComparison.Ordinal);
        Assert.Contains("North", text, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Writes_a_table_with_a_repeating_header_row()
    {
        using var stream = await ExportAsync(TestData.Request(TestData.SalesTable(4)));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);
        var table = Body(package).Elements<Table>().Single();
        var rows = table.Elements<TableRow>().ToArray();

        Assert.Equal(5, rows.Length);
        Assert.NotNull(rows[0].TableRowProperties?.GetFirstChild<TableHeader>());
        Assert.Equal(8, rows[0].Elements<TableCell>().Count());
        Assert.Contains("Region", rows[0].InnerText, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Headings_carry_an_outline_level_for_navigation()
    {
        using var stream = await ExportAsync(TestData.Request(TestData.SalesDocument(1)));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);

        var outlined = Body(package)
            .Elements<Paragraph>()
            .Where(p => p.ParagraphProperties?.GetFirstChild<OutlineLevel>() is not null)
            .ToArray();

        Assert.NotEmpty(outlined);
        Assert.Contains(outlined, p => p.InnerText.Contains("Summary", StringComparison.Ordinal));
    }

    [Fact]
    public async Task Writes_a_page_header_and_a_footer_with_page_fields()
    {
        using var stream = await ExportAsync(TestData.Request(TestData.SalesDocument(1)));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);
        var mainPart = package.MainDocumentPart!;

        var header = Assert.Single(mainPart.HeaderParts);
        Assert.Contains("Quarterly sales", header.Header!.InnerText, StringComparison.Ordinal);

        var footer = Assert.Single(mainPart.FooterParts);
        var fields = footer.Footer!.Descendants<SimpleField>().Select(f => f.Instruction?.Value).ToArray();
        Assert.Contains("PAGE", fields);
        Assert.Contains("NUMPAGES", fields);
        Assert.Contains("Generated by Albin.Export", footer.Footer.InnerText, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Page_numbers_and_header_can_be_suppressed()
    {
        var options = new WordExportOptions { IncludePageNumbers = false, HeaderText = string.Empty, FooterText = string.Empty };
        using var stream = await ExportAsync(TestData.Request(TestData.SalesTable(1), options));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);

        Assert.Empty(package.MainDocumentPart!.HeaderParts);
        Assert.Empty(package.MainDocumentPart.FooterParts);
    }

    [Fact]
    public async Task Applies_page_size_orientation_and_margins()
    {
        var options = new WordExportOptions { PageSize = ExportPageSize.Letter, Landscape = true, Margin = 36d };
        using var stream = await ExportAsync(TestData.Request(TestData.SalesTable(1), options));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);

        var properties = Body(package).Elements<SectionProperties>().Single();
        var pageSize = properties.GetFirstChild<PageSize>()!;
        var margin = properties.GetFirstChild<PageMargin>()!;

        Assert.Equal(15840U, pageSize.Width!.Value);
        Assert.Equal(12240U, pageSize.Height!.Value);
        Assert.Equal(PageOrientationValues.Landscape, pageSize.Orient!.Value);
        Assert.Equal(720, margin.Top!.Value);
    }

    [Fact]
    public async Task Embeds_images_and_charts_as_inline_pictures()
    {
        var png = Albin.Export.Chart.ChartPngRenderer.Render(TestData.RevenueChart());
        var document = ExportDocument.Builder("With media")
            .Chart(TestData.RevenueChart())
            .Image(png, "image/png", "revenue chart")
            .Build();

        using var stream = await ExportAsync(TestData.Request(document));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);
        var mainPart = package.MainDocumentPart!;

        Assert.Equal(2, mainPart.ImageParts.Count());
        var drawings = Body(package).Descendants<Drawing>().ToArray();
        Assert.Equal(2, drawings.Length);

        var extent = drawings[0].Descendants<DocumentFormat.OpenXml.Drawing.Wordprocessing.Extent>().Single();
        Assert.True(extent.Cx!.Value > 0);
        Assert.True(extent.Cy!.Value > 0);
    }

    [Fact]
    public async Task Sets_package_metadata()
    {
        var options = new WordExportOptions { Author = "Albin" };
        using var stream = await ExportAsync(TestData.Request(TestData.SalesDocument(1), options));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);

        Assert.Equal("Quarterly sales", package.PackageProperties.Title);
        Assert.Equal("Albin", package.PackageProperties.Creator);
    }

    [Fact]
    public async Task Round_trips_unicode_and_reports_empty_tables()
    {
        using var stream = await ExportAsync(TestData.Request(TestData.UnicodeTable()));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);
        Assert.Contains("日本語のテキスト", Body(package).InnerText, StringComparison.Ordinal);

        using var emptyStream = await ExportAsync(TestData.Request(ExportTable.Empty(["A"], "Empty")));
        using var emptyPackage = WordprocessingDocument.Open(emptyStream, isEditable: false);
        Assert.Contains("No data.", Body(emptyPackage).InnerText, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Writes_page_breaks()
    {
        var document = ExportDocument.Builder("Paged")
            .Paragraph("first")
            .PageBreak()
            .Paragraph("second")
            .Build();

        using var stream = await ExportAsync(TestData.Request(document));
        using var package = WordprocessingDocument.Open(stream, isEditable: false);

        Assert.Single(Body(package).Descendants<Break>(), b => b.Type?.Value == BreakValues.Page);
    }

    [Fact]
    public async Task Writes_to_a_non_seekable_destination()
    {
        using var inner = new MemoryStream();
        await using (var destination = new WriteOnlyStream(inner))
        {
            await _exporter.ExportAsync(TestData.Request(TestData.SalesTable(2)), destination);
        }

        inner.Position = 0;
        using var package = WordprocessingDocument.Open(inner, isEditable: false);
        Assert.Contains("North", Body(package).InnerText, StringComparison.Ordinal);
    }

    [Fact]
    public async Task Honours_cancellation()
    {
        using var cts = new CancellationTokenSource();
        await cts.CancelAsync();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(
            () => TestData.RenderAsync(_exporter, TestData.Request(TestData.SalesTable(50)), cts.Token));
    }

    private async Task<MemoryStream> ExportAsync(ExportRequest request)
    {
        var stream = new MemoryStream();
        await _exporter.ExportAsync(request, stream);
        stream.Position = 0;
        return stream;
    }

    private static Body Body(WordprocessingDocument package)
    {
        var body = package.MainDocumentPart?.Document?.Body;
        Assert.NotNull(body);
        return body;
    }
}
