namespace Albin.Export.Tests;

public sealed record SalesRecord(
    int Id,
    string Region,
    string Product,
    DateTime Date,
    int Units,
    decimal Revenue,
    decimal? Margin,
    bool Active);

public sealed class AttributedDto
{
    [ExportColumn(Header = "Identifier", Order = -1)]
    public int Id { get; set; }

    public string Name { get; set; } = string.Empty;

    [ExportColumn(Header = "Amount", Format = "N2", Alignment = ExportAlignment.Right)]
    public decimal Total { get; set; }

    [ExportIgnore]
    public string Secret { get; set; } = "hidden";
}

internal static class TestData
{
    public static IReadOnlyList<SalesRecord> Sales(int count = 5)
    {
        var regions = new[] { "North", "South", "East", "West" };
        var products = new[] { "Widget", "Gadget", "Doohickey" };
        var records = new List<SalesRecord>(count);

        for (var i = 0; i < count; i++)
        {
            records.Add(new SalesRecord(
                i + 1,
                regions[i % regions.Length],
                products[i % products.Length],
                new DateTime(2026, 1, 1, 8, 30, 0, DateTimeKind.Utc).AddDays(i),
                (i * 7 % 40) + 1,
                decimal.Round(100.5m + (i * 13.37m), 2),
                i % 4 == 0 ? null : decimal.Round(0.1m + (i % 9 * 0.03m), 3),
                i % 3 != 0));
        }

        return records;
    }

    public static ExportTable SalesTable(int count = 5) => ExportTable
        .Create(Sales(count), "Sales")
        .Column("Id", x => x.Id)
        .Column("Region", x => x.Region)
        .Column("Product", x => x.Product)
        .Column("Date", x => x.Date, format: "yyyy-MM-dd")
        .Column("Units", x => x.Units)
        .Column("Revenue", x => x.Revenue, format: "N2", alignment: ExportAlignment.Right)
        .Column("Margin", x => x.Margin, format: "P1", alignment: ExportAlignment.Right)
        .Column("Active", x => x.Active)
        .Build();

    public static ExportDocument SalesDocument(int count = 5) => ExportDocument.Builder("Quarterly sales")
        .Subtitle("Q1 2026, all regions")
        .Footer("Generated by Albin.Export")
        .Heading("Summary", 2)
        .Paragraph("Revenue grew across every region.")
        .Table(SalesTable(count))
        .Chart(RevenueChart())
        .Build();

