    public static async Task<byte[]> RenderAsync(
        IExporter exporter,
        ExportRequest request,
        CancellationToken cancellationToken = default)
    {
        using var buffer = new MemoryStream();
        await exporter.ExportAsync(request, buffer, cancellationToken);
        return buffer.ToArray();
    }

    public static async Task<string> RenderTextAsync(
        IExporter exporter,
        ExportRequest request,
        CancellationToken cancellationToken = default)
    {
        var bytes = await RenderAsync(exporter, request, cancellationToken);
        return StripBom(Encoding.UTF8.GetString(bytes));
    }

    public static string StripBom(string value)
        => value.Length > 0 && value[0] == '\uFEFF' ? value[1..] : value;

    public static ExportRequest Request(ExportTable table, ExportOptions? options = null)
        => new(ExportDocument.FromTable(table), options);

    public static ExportRequest Request(ExportDocument document, ExportOptions? options = null)
        => new(document, options);

    public static async IAsyncEnumerable<SalesRecord> SalesAsync(
        int count,
        [EnumeratorCancellation] CancellationToken cancellationToken = default)
    {
        foreach (var record in Sales(count))
        {
            cancellationToken.ThrowIfCancellationRequested();
            await Task.Yield();
            yield return record;
        }
    }

    public static string Invariant(FormattableString value)
        => value.ToString(CultureInfo.InvariantCulture);

    public static ExportOptions OptionsFor(ExportFormat format) => format switch
    {
        ExportFormat.Csv => new CsvExportOptions(),
        ExportFormat.Json => new JsonExportOptions(),
        ExportFormat.Xml => new XmlExportOptions(),
        ExportFormat.Markdown => new MarkdownExportOptions(),
        ExportFormat.Html => new HtmlExportOptions(),
        ExportFormat.Excel => new ExcelExportOptions(),
        ExportFormat.Word => new WordExportOptions(),
        ExportFormat.Pdf => new PdfExportOptions(),
        ExportFormat.Png or ExportFormat.Svg or ExportFormat.ECharts => new ChartExportOptions(),
        ExportFormat.Zip => new ZipExportOptions
        {
            Entries = [ZipEntrySource.FromText("a.txt", "content")],
        },
        _ => new ExportOptions(),
    };
}
